#!/usr/bin/env python3
"""build_selfcontained_deploy.py — emit a deploy module with the zip embedded.

The System page's CSP allows module scripts from 127.0.0.1 but not XHR/fetch to
it, so a normal deploy script cannot download the package. This bakes the signed
application.zip (and manifest) into the module as base64; the module writes it
via DeviceStorage and swaps vroot/keyboard, reporting with console.log (which
reaches logcat).

Usage: python3 tools/build_selfcontained_deploy.py
Output: build/deploy_selfcontained.js
"""
import base64
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ZIP = os.path.join(ROOT, "build", "deploy", "application.zip")
MAN = os.path.join(ROOT, "app", "manifest.webmanifest")
OUT = os.path.join(ROOT, "build", "deploy_selfcontained.js")

zip_b64 = base64.b64encode(open(ZIP, "rb").read()).decode()
man_b64 = base64.b64encode(open(MAN, "rb").read()).decode()

template = r'''/**
 * deploy_selfcontained.js — generated by tools/build_selfcontained_deploy.py.
 * Embeds the signed keyboard package and installs it into vroot/keyboard.
 * No network access; reports via console.log.
 */
const ZIP_B64 = "__ZIP__";
const MAN_B64 = "__MAN__";
const STAMP = Date.now();
const STAGE = "keyboard.stage";
const BACKUP = "keyboard.stock";

function rep(msg) {
  try { console.log("[kbdeploy] " + msg); } catch (e) {}
}
function b64ToBytes(b64) {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
const isDir = (e) => !!e && typeof e.getFilesAndDirectories === "function";

async function entryOrNull(dir, name) {
  try { return await dir.get(name); } catch (e) { return null; }
}

function readBytes(file) {
  return new Promise((resolve, reject) => {
    if (!file || isDir(file)) { reject(new Error("not a file")); return; }
    const r = new FileReader();
    r.onload = () => resolve(new Uint8Array(r.result));
    r.onerror = () => reject(r.error || new Error("read failed"));
    r.readAsArrayBuffer(file);
  });
}

function storageRoot() {
  if (!navigator.b2g) throw new Error("navigator.b2g missing");
  if (typeof navigator.b2g.getDeviceStorage === "function") {
    const ds = navigator.b2g.getDeviceStorage("apps");
    if (ds) return ds.getRoot();
  }
  if (typeof navigator.b2g.getDeviceStorages === "function") {
    const arr = navigator.b2g.getDeviceStorages("apps");
    if (arr && arr[0]) return arr[0].getRoot();
  }
  throw new Error("apps DeviceStorage not available on this page");
}

rep("module loaded href=" + location.href);

async function main() {
  rep("start href=" + location.href);
  const zipBytes = b64ToBytes(ZIP_B64);
  const manBytes = b64ToBytes(MAN_B64);
  rep("payload zip=" + zipBytes.length + " manifest=" + manBytes.length);

  const root = await storageRoot();
  rep("root ok=" + !!root);
  const vroot = await root.get("local/webapps/vroot");
  if (!isDir(vroot)) throw new Error("vroot is not a directory");
  rep("vroot ok");

  const oldStage = await entryOrNull(vroot, STAGE);
  if (oldStage) { rep("removing old stage"); await vroot.removeDeep(STAGE); }
  const stage = await vroot.createDirectory(STAGE);
  await stage.createFile("application.zip", {
    ifExists: "fail",
    data: new Blob([zipBytes], { type: "application/zip" }),
  });
  await stage.createFile("manifest.webmanifest", {
    ifExists: "fail",
    data: new Blob([manBytes], { type: "application/manifest+json" }),
  });
  const staged = await readBytes(await stage.get("application.zip"));
  if (staged.length !== zipBytes.length || staged[0] !== 0x50 || staged[1] !== 0x4b) {
    throw new Error("staged zip verify failed: " + staged.length);
  }
  rep("staged " + staged.length + " bytes, PK ok");

  const current = await entryOrNull(vroot, "keyboard");
  if (!current) throw new Error("vroot/keyboard missing");
  const existingBackup = await entryOrNull(vroot, BACKUP);
  if (!existingBackup) {
    const ok = await vroot.renameTo("keyboard", BACKUP);
    rep("saved stock symlink as " + BACKUP + " -> " + ok);
    if (!ok) throw new Error("could not move keyboard to " + BACKUP);
  } else {
    const prev = "keyboard.previous-" + STAMP;
    const ok = await vroot.renameTo("keyboard", prev);
    rep("kept existing backup; moved current to " + prev + " -> " + ok);
    if (!ok) throw new Error("could not move current keyboard aside");
  }

  let swapped = false;
  try {
    const ok = await vroot.renameTo(STAGE, "keyboard");
    rep("renamed stage -> keyboard: " + ok);
    if (!ok) throw new Error("rename returned false");
    swapped = true;
  } catch (e) {
    rep("SWAP FAILED: " + e);
    try {
      if (!(await entryOrNull(vroot, "keyboard"))) {
        await vroot.renameTo(BACKUP, "keyboard");
        rep("restored stock symlink");
      }
    } catch (e2) { rep("RESTORE FAILED: " + e2); }
    throw e;
  }

  const kb = await vroot.get("keyboard");
  const bytes = await readBytes(await kb.get("application.zip"));
  rep("vroot/keyboard/application.zip now " + bytes.length + " (expected " + zipBytes.length + ")");
  if (!swapped || bytes.length !== zipBytes.length) throw new Error("final size mismatch");
  rep("DEPLOY OK — reboot the phone");
}

main().catch((e) => rep("DEPLOY FAILED: " + (e && (e.name + ": " + e.message || e))));
'''

code = template.replace("__ZIP__", zip_b64).replace("__MAN__", man_b64)
open(OUT, "w").write(code)
print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes), zip {len(zip_b64)} b64 chars")
